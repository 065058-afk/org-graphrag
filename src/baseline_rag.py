from llama_index.core import (SimpleDirectoryReader, VectorStoreIndex, Settings,
                              StorageContext, Document)
from llama_index.core.node_parser import SentenceSplitter
from llama_index.embeddings.huggingface import HuggingFaceEmbedding
from llama_index.vector_stores.postgres import PGVectorStore
from config import (POSTGRES_HOST, POSTGRES_PORT, POSTGRES_USER,
                    POSTGRES_PASSWORD, POSTGRES_DB)
from src.llm import chat

Settings.embed_model = HuggingFaceEmbedding(model_name="BAAI/bge-small-en-v1.5")
Settings.llm = None  # answers are generated by src/llm.py

_index_cache = None

def get_vector_store():
    return PGVectorStore.from_params(
        host=POSTGRES_HOST, port=POSTGRES_PORT, user=POSTGRES_USER,
        password=POSTGRES_PASSWORD, database=POSTGRES_DB,
        table_name="baseline_chunks", embed_dim=384,
    )

def get_baseline_index():
    global _index_cache
    if _index_cache is None:
        vector_store = get_vector_store()
        storage_context = StorageContext.from_defaults(vector_store=vector_store)
        _index_cache = VectorStoreIndex.from_vector_store(vector_store, storage_context=storage_context)
    return _index_cache

def build_baseline_index_once():
    docs = SimpleDirectoryReader("data/parsed").load_data()
    nodes = SentenceSplitter(chunk_size=500, chunk_overlap=50).get_nodes_from_documents(docs)
    vector_store = get_vector_store()
    storage_context = StorageContext.from_defaults(vector_store=vector_store)
    VectorStoreIndex(nodes, storage_context=storage_context)
    print(f"Indexed {len(nodes)} chunks into Postgres (pgvector)")

def add_document_to_baseline(text: str, filename: str):
    nodes = SentenceSplitter(chunk_size=500, chunk_overlap=50).get_nodes_from_documents(
        [Document(text=text, metadata={"file_name": filename})])
    index = get_baseline_index()
    for node in nodes:
        index.insert_nodes([node])
    return len(nodes)

def baseline_answer(question: str, top_k: int = 5):
    index = get_baseline_index()
    nodes = index.as_retriever(similarity_top_k=top_k).retrieve(question)
    chunks = [n.get_content() for n in nodes]
    if not chunks:
        return "I don't have information on that in the ingested documents.", []
    context = "\n\n---\n\n".join(chunks)
    prompt = f"""Answer the question using only the context below. Cite which section the info came from.

Context:
{context}

Question: {question}"""
    return chat(prompt), chunks

if __name__ == "__main__":
    build_baseline_index_once()
